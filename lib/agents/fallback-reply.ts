  "ขอโทษนะ ตอนนี้เชื่อมต่อไม่ได้ชั่วคราว แต่คุณไม่ได้อยู่คนเดียว สายด่วนสุขภาพจิต 1323 พร้อมคุยด้วยตลอด 24 ชม. ไม่มีค่าใช้จ่าย เดี๋ยวลองใหม่อีกทีนะ",
